package iconuse

import "aego/engine/module"

const Owner = "editor"

type Reservation struct {
	ID     string
	Reason string
	Until  string
}

var Reserved = []Reservation{}

func Uses() []module.IconUse {
	out := append([]module.IconUse(nil), Editor...)
	for _, r := range Reserved {
		out = append(out, module.IconUse{ID: r.ID, Owner: Owner, By: "reserved until Stage " + r.Until + ": " + r.Reason, Size: 16})
	}
	return out
}

func use(id string, size int, by string) module.IconUse {
	return module.IconUse{ID: id, Owner: Owner, By: by, Size: size}
}

